import { writeFileSync } from 'node:fs';

// Generates packages/sim/src/tables.ts (ARCHITECTURE §4.4): transcendental functions are evaluated here, once, in
// Node, and checked in as literals, so the sim itself never calls Math.exp. Re-run only when a table changes:
//   pnpm exec tsx tools/gen-tables.ts && pnpm format

/** 1 − e^(−u) for u in [0, U_MAX], sampled every U_MAX / (N − 1). Used by the speed curve (GDD §5.2). */
const N = 513;
const U_MAX = 8;
const values = Array.from({ length: N }, (_, i) => 1 - Math.exp(-(i * U_MAX) / (N - 1)));
const COS_N = 1801;
const cosine = Array.from({ length: COS_N }, (_, i) =>
  i === 0 ? 1 : i === COS_N - 1 ? 0 : Math.cos((i * Math.PI) / (2 * (COS_N - 1))),
);
const cosHalfAngleStep = Math.PI / (2 * (COS_N - 1));

const body = `// Generated by tools/gen-tables.ts — do not edit by hand. Hash-tested in tables.test.ts.

/** Samples of 1 − e^(−u) for u = i · SAT_EXP_STEP, i = 0 … ${N - 1}. */
export const SAT_EXP: readonly number[] = [
${values.map((v) => `  ${v},`).join('\n')}
];

/** Spacing of SAT_EXP in u. */
export const SAT_EXP_STEP = ${U_MAX / (N - 1)};

/** Largest u covered by SAT_EXP; beyond it the curve is treated as saturated. */
export const SAT_EXP_MAX = ${U_MAX};

/** Magnitude of cos(pi * turns), sampled on turns [0, 0.5]; exact quadrant endpoints. */
export const COS_HALF_TURN: readonly number[] = [
${cosine.map((v) => `  ${v},`).join('\n')}
];

/** 0.05 degrees of half-angle per sample. */
export const COS_HALF_TURN_STEP = ${0.5 / (COS_N - 1)};

/** Linear interpolation error <= h^2/8 because |cos''| <= 1; h is the half-angle step in radians. */
export const COS_HALF_TURN_ERROR = ${(cosHalfAngleStep * cosHalfAngleStep) / 8};
`;
writeFileSync('packages/sim/src/tables.ts', body);
console.log(`wrote ${N} exponential and ${COS_N} cosine samples`);
